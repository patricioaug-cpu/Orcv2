// Generate StructureComposition objects for all catalog mnemonics
export function generateExtendedCompositions(): Record<string, StructureComposition> {
  const result: Record<string, StructureComposition> = {};

  Object.entries(EXTENDED_CEMIG_MNEMONICS).forEach(([code, desc]) => {
    let type = "ESTRUTURA";
    if (code.startsWith("MOC") || code.startsWith("US")) type = "MÃO DE OBRA";
    else if (code.startsWith("TR") || code.startsWith("C2TR")) type = "TRAFO";
    else if (code.startsWith("PC") || code.startsWith("PD") || code.startsWith("PM")) type = "POSTE";
    else if (code.startsWith("CA") || code.startsWith("CAA") || code.startsWith("CAP")) type = "CONDUTOR";

    result[code] = {
      structureCode: code,
      structureName: desc,
      type,
      items: [
        {
          code: `MNE-${code}`,
          description: desc,
          unit: type === "CONDUTOR" ? "M" : type === "MÃO DE OBRA" ? "H" : "UN",
          qtyPerUnit: 1,
        },
      ],
    };
  });

  return result;
}
